// Stamps the poster number onto each stop of a TJ corridor. Stops with no
// number keep `pos: ''` (the corridor is real but the poster doesn't print a
// code for it — e.g. feeder-only stops on a BRT corridor).
export function withStationNumbers(line: LineTopology): LineTopology {
  const stamp = (s: Stop): Stop => {
    const pos = TJ_STATION_NUMBERS[`${line.lineCode}:${s.station}`]
    return pos ? { ...s, pos } : s
  }
  return {
    ...line,
    path: line.path.map(stamp),
    ...(line.pathReverse ? { pathReverse: line.pathReverse.map(stamp) } : {}),
    ...(line.branches ? { branches: line.branches.map(b => ({ ...b, path: b.path.map(stamp) })) } : {})
  }
}
